const collection = JSON.parse(readFileSync(source, "utf8"))
const width = collection.width ?? 24
const height = collection.height ?? 24

const wanted = new Set([...Object.values(BY_NAME), ...Object.values(BY_EXTENSION)])
const missing = [...wanted].filter((name) => !collection.icons[name])
if (missing.length > 0) {
  // A renamed upstream icon must fail the build rather than ship a blank
  // square: the table above is the only place that knows the name is wrong.
  console.error(`Unknown vscode-icons names:\n  ${missing.join("\n  ")}`)
  process.exit(1)
}

const icons = [...wanted].sort()
const bodies = icons
  .map((name) => {
    const icon = collection.icons[name]
    const w = icon.width ?? width
    const h = icon.height ?? height
    return `  ${JSON.stringify(name)}: { body: ${JSON.stringify(icon.body)}, viewBox: "0 0 ${w} ${h}" },`
  })
  .join("\n")

const entries = (table) =>
  Object.entries(table)
    .map(([key, name]) => `  ${JSON.stringify(key)}: ${JSON.stringify(name)},`)
    .join("\n")

const output = `/* eslint-disable */
// GENERATED by scripts/build-file-icons.mjs — do not edit by hand.
// Source: vscode-icons, via @iconify-json/vscode-icons (MIT).
// Regenerate with \`pnpm icons:build\`.

export interface FileIconData {
  /** Inner SVG markup, from the icon set. */
  body: string
  viewBox: string
}

export const FILE_ICONS: Record<string, FileIconData> = {
${bodies}
}

/** Exact file names, lowercased. Checked before the extension table. */
export const ICON_BY_NAME: Record<string, string> = {
${entries(BY_NAME)}
}

export const ICON_BY_EXTENSION: Record<string, string> = {
${entries(BY_EXTENSION)}
}
`

writeFileSync(target, output)
console.log(`Wrote ${icons.length} icons to ${target} (${(output.length / 1024).toFixed(1)} KB)`)
