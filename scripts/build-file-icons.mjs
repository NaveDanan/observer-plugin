// Generates `apps/web/src/chat/fileIcons.generated.ts` from the vscode-icons
// set shipped by `@iconify-json/vscode-icons`.
//
// The whole collection is 1,585 icons and 3.7 MB — far too much to ship to a
// 420px panel, and Vite cannot tree-shake a JSON blob. So the subset below is
// extracted at build time and committed as a plain module: the icon library
// stays a devDependency, the app ships ~50 KB of inline SVG, and nothing is
// fetched at runtime (docs/privacy.md: Observer makes no outbound calls).
//
// Run with `pnpm icons:build` after changing the tables below.

